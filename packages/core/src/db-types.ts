/**
 * Row types for every table created by `applySchema()` and `applyMetricsSchema()`,
 * used as the `DB` parameter of the compile-only Kysely builder in
 * `query-builder.ts`.
 *
 * `BOUND_TABLE_COLUMNS` is the single source: the TypeScript row types are
 * derived from it, and `__tests__/db-types.test.ts` compares it against
 * `PRAGMA table_info` on a fresh schema so a column added, dropped, retyped, or
 * re-nulled in the DDL fails CI until this file follows.
 *
 * Column specs name the declared STRICT type, with a trailing `?` when the
 * column admits NULL. Primary-key columns are non-null. `untyped` covers FTS5
 * virtual-table columns, which carry no declared type. FTS5 shadow tables
 * (`<fts>_config`, `_content`, `_data`, `_docsize`, `_idx`) are SQLite internals
 * and are not modelled.
 */

